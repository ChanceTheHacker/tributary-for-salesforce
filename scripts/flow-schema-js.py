#!/usr/bin/env python3
"""Generate lwc/flowSchema/flowSchema.js from a Metadata API WSDL.

Usage: scripts/flow-schema-js.py metadata.wsdl > force-app/main/default/lwc/flowSchema/flowSchema.js

The module lists, for Flow and every type reachable from it, the fields in
the order the Metadata API writes them (inherited fields first), with each
field's type and whether it repeats. flowXml uses it to write flow metadata
as the XML Salesforce produces and to read that XML back into JSON.
"""
import json
import re
import sys
import xml.etree.ElementTree as ET

XSD = "{http://www.w3.org/2001/XMLSchema}"
WSDL = "{http://schemas.xmlsoap.org/wsdl/}"
PRIMITIVES = {"string", "boolean", "int", "long", "double", "date", "dateTime", "time", "base64Binary", "anyType"}


def local(qname):
    return qname.split(":", 1)[-1] if qname else None


def main(path):
    root = ET.parse(path).getroot()
    complex_types, simple_types = {}, set()
    for schema in root.find(f"{WSDL}types").findall(f"{XSD}schema"):
        for node in schema.findall(f"{XSD}complexType"):
            complex_types[node.get("name")] = node
        for node in schema.findall(f"{XSD}simpleType"):
            simple_types.add(node.get("name"))
    with open(path, encoding="utf-8") as fh:
        version = re.search(r"Metadata API version ([\d.]+)", fh.read(2048))

    def fields(name):
        node = complex_types[name]
        ext = node.find(f".//{XSD}extension")
        out = []
        if ext is not None and local(ext.get("base")) in complex_types:
            out = fields(local(ext.get("base")))
        seq = node.find(f".//{XSD}sequence")
        for el in (seq.findall(f"{XSD}element") if seq is not None else []):
            typ = local(el.get("type"))
            if typ in simple_types:
                typ = "string"
            out.append((el.get("name"), typ, el.get("maxOccurs") == "unbounded"))
        # A type can redeclare a field it inherits (FlowCustomError repeats
        # description); the API writes it once, in the inherited position.
        seen = set()
        return [f for f in out if not (f[0] in seen or seen.add(f[0]))]

    types, queue = {}, ["Flow"]
    while queue:
        name = queue.pop()
        if name in types:
            continue
        types[name] = fields(name)
        for _, typ, _ in types[name]:
            if typ in complex_types and typ not in types:
                queue.append(typ)
            elif typ not in complex_types and typ not in PRIMITIVES:
                raise SystemExit(f"unknown type {typ} in {name}")

    lines = [
        f"// Generated by scripts/flow-schema-js.py from the Metadata API {version.group(1) if version else ''} WSDL. Do not edit.",
        "//",
        "// TYPES[type] lists the type's fields in XML order as \"name:type\", with a",
        "// trailing * on fields that repeat. Types not listed here are primitives.",
        "export const TYPES = Object.freeze({",
    ]
    for name in sorted(types):
        spec = ",".join(f"{f}:{t}{'*' if many else ''}" for f, t, many in types[name])
        lines.append(f"  {name}: {json.dumps(spec)},")
    lines.append("});")
    print("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1])

#!/usr/bin/env python3
"""Render the Flow metadata schema from a Metadata API WSDL as Markdown.

Usage: scripts/flow-schema.py metadata.wsdl > docs/reference/flow-metadata-schema-vNN.md

Download the WSDL from the target org (Setup > API > Generate Metadata WSDL).
The WSDL itself is not committed; only the derived reference is.
"""
import re
import sys
import xml.etree.ElementTree as ET

XSD = "{http://www.w3.org/2001/XMLSchema}"
WSDL = "{http://schemas.xmlsoap.org/wsdl/}"


def local(qname):
    return qname.split(":", 1)[-1] if qname else None


def main(path):
    root = ET.parse(path).getroot()
    complex_types, simple_types = {}, {}
    for schema in root.find(f"{WSDL}types").findall(f"{XSD}schema"):
        for node in schema.findall(f"{XSD}complexType"):
            complex_types[node.get("name")] = node
        for node in schema.findall(f"{XSD}simpleType"):
            simple_types[node.get("name")] = node

    with open(path, encoding="utf-8") as fh:
        version = re.search(r"Metadata API version ([\d.]+)", fh.read(2048))
    version = version.group(1) if version else "unknown"

    def is_flow(name):
        return name.startswith("Flow")

    referenced_enums = set()
    out = [f"# Flow metadata schema (Metadata API {version})", ""]
    out.append("Generated by `scripts/flow-schema.py` from the org's Metadata WSDL. Do not edit by hand.")
    out.append("")
    out.append("## Complex types")
    out.append("")
    for name in sorted(n for n in complex_types if is_flow(n)):
        node = complex_types[name]
        ext = node.find(f".//{XSD}extension")
        base = local(ext.get("base")) if ext is not None else None
        out.append(f"### {name}" + (f" (extends {base})" if base else ""))
        out.append("")
        out.append("| Field | Type | Many | Optional |")
        out.append("|---|---|---|---|")
        for el in node.iter(f"{XSD}element"):
            typ = local(el.get("type"))
            if typ in simple_types:
                referenced_enums.add(typ)
            many = "yes" if el.get("maxOccurs") == "unbounded" else ""
            optional = "yes" if el.get("minOccurs") == "0" else ""
            out.append(f"| {el.get('name')} | {typ} | {many} | {optional} |")
        out.append("")

    out.append("## Enumerations")
    out.append("")
    for name in sorted(n for n in simple_types if is_flow(n) or n in referenced_enums):
        values = [e.get("value") for e in simple_types[name].iter(f"{XSD}enumeration")]
        if not values:
            continue
        out.append(f"### {name} ({len(values)})")
        out.append("")
        out.append(", ".join(f"`{v}`" for v in values))
        out.append("")
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
